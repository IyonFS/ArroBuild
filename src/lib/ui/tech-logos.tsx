export function resolveTechSlug(name: string): string | null {
  const key = name.toLowerCase().trim();
  return SLUG_ALIASES[key] ?? (LOGOS[key] ? key : null);
}

export function TechLogo({
  name,
  size = 16,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const slug = resolveTechSlug(name);
  if (!slug || !LOGOS[slug]) {
    return (
      <span
        className={className}
        style={{
          width: size,
          height: size,
          borderRadius: 4,
          background: "var(--app-bg-hover)",
          display: "inline-block",
          fontSize: size * 0.55,
          lineHeight: `${size}px`,
          textAlign: "center",
          color: "var(--app-text-tertiary)",
        }}
      >
        {name.charAt(0)}
      </span>
    );
  }
  const logo = LOGOS[slug];
  return (
    <svg
      width={size}
      height={size}
      viewBox={logo.viewBox}
      className={className}
      aria-hidden
    >
      <path fill={logo.color} d={logo.path} />
    </svg>
  );
}

export function TechLogoStack({
  names,
  size = 14,
  className,
}: {
  names: string[];
  size?: number;
  className?: string;
}) {
  const slugs = names.map(resolveTechSlug).filter(Boolean).slice(0, 4);
  if (slugs.length === 0) return null;
  return (
    <div className={`flex items-center -space-x-1.5 ${className ?? ""}`}>
      {slugs.map((_, i) => (
        <span
          key={`${names[i]}-${i}`}
          className="inline-flex items-center justify-center rounded-md"
          style={{
            width: size + 6,
            height: size + 6,
            background: "var(--app-bg-elevated)",
            border: "1px solid var(--app-border-default)",
            zIndex: slugs.length - i,
          }}
        >
          <TechLogo name={names[i]} size={size} />
        </span>
      ))}
    </div>
  );
}
